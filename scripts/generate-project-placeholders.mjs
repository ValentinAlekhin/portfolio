import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, extname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const projectsDirectory = join(repositoryRoot, 'public', 'projects')
const outputFile = join(repositoryRoot, 'app', 'data', 'projectPlaceholders.generated.ts')
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp'])

function tsString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll(/'/g, '\\x27')}'`
}

async function collectImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const images = []

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) images.push(...await collectImages(path))
    else if (entry.isFile() && imageExtensions.has(extname(entry.name).toLowerCase())) images.push(path)
  }

  return images
}

async function generate() {
  const images = await collectImages(projectsDirectory)
  const placeholders = {}

  for (const path of images) {
    const publicPath = `/projects/${relative(projectsDirectory, path).split(sep).join('/')}`
    const thumbnail = await sharp(path)
      .rotate()
      .resize({ width: 32, height: 32, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 38, effort: 4 })
      .toBuffer()
    placeholders[publicPath] = `data:image/webp;base64,${thumbnail.toString('base64')}`
  }

  const entries = Object.entries(placeholders)
    .map(([source, dataUrl]) => `  ${tsString(source)}: ${tsString(dataUrl)},`)
  const content = [
    '// Generated by scripts/generate-project-placeholders.mjs. Do not edit by hand.',
    'export const projectPlaceholders: Readonly<Record<string, string>> = {',
    ...entries,
    '}',
    '',
  ].join('\n')

  let existing = ''
  try {
    existing = await readFile(outputFile, 'utf8')
  }
  catch (error) {
    if (error.code !== 'ENOENT') throw error
  }

  if (existing !== content) await writeFile(outputFile, content)
}

await generate()
