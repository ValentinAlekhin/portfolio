import type { Project, ProjectMedia, ProjectMediaDisplay, ProjectMediaSources, ProjectMediaTheme } from '../types/content'
import { LocaleCode } from '../types/i18n'

function planesArchMediaPath(id: string, locale: LocaleCode, theme: ProjectMediaTheme) {
  return `/projects/planes-arch/planes-arch-${id}-${locale}-${theme}.webp`
}

function planesArchMediaSources(id: string): ProjectMediaSources {
  return {
    [LocaleCode.Ru]: {
      light: planesArchMediaPath(id, LocaleCode.Ru, 'light'),
      dark: planesArchMediaPath(id, LocaleCode.Ru, 'dark'),
    },
    [LocaleCode.En]: {
      light: planesArchMediaPath(id, LocaleCode.En, 'light'),
      dark: planesArchMediaPath(id, LocaleCode.En, 'dark'),
    },
  }
}

type VisualProjectSlug = 'aerovista' | 'cnp' | 'fgisu' | 'forma' | 'kineo' | 'nordhus'

function visualProjectMedia(
  project: VisualProjectSlug,
  id: string,
  width: number,
  height: number,
  display: ProjectMediaDisplay,
  file = id,
): ProjectMedia {
  return {
    id,
    src: `/projects/${project}/${file}.webp`,
    width,
    height,
    display,
    altKey: `projects.entries.${project}.media.${id}.alt`,
    captionKey: `projects.entries.${project}.media.${id}.caption`,
    descriptionKey: `projects.entries.${project}.media.${id}.description`,
  }
}

function cnpPublishedPhoto(id: string, file: string, width: number, height: number, url: string): ProjectMedia {
  return {
    ...visualProjectMedia('cnp', id, width, height, 'viewport', file),
    attribution: { labelKey: `projects.entries.cnp.media.${id}.source`, url },
  }
}

